DROP TABLE YEUCAUHOTRO CASCADE CONSTRAINTS;
DROP TABLE LICHSUTRANGTHAIDH CASCADE CONSTRAINTS;
DROP TABLE THANHTOAN CASCADE CONSTRAINTS;
DROP TABLE PHUONGTHUCTT CASCADE CONSTRAINTS;
DROP TABLE CHITIETDH CASCADE CONSTRAINTS;
DROP TABLE DONHANG CASCADE CONSTRAINTS;
DROP TABLE MAGIAMGIA CASCADE CONSTRAINTS;
DROP TABLE CHITIETKHUYENMAI CASCADE CONSTRAINTS;
DROP TABLE KHUYENMAI CASCADE CONSTRAINTS;
DROP TABLE DANHGIA CASCADE CONSTRAINTS;
DROP TABLE MONAN CASCADE CONSTRAINTS;
DROP TABLE DANHMUC CASCADE CONSTRAINTS;
DROP TABLE DIACHI CASCADE CONSTRAINTS;
DROP TABLE NGUOIDUNG CASCADE CONSTRAINTS;
DROP TABLE VAITRO CASCADE CONSTRAINTS;

CREATE TABLE VAITRO (
    MaVT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenVT VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE NGUOIDUNG (
    MaTK NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Password VARCHAR2(255) NOT NULL,
    HoTen VARCHAR2(100) NOT NULL,
    SDT VARCHAR2(15),
    Email VARCHAR2(100) NOT NULL UNIQUE,
    TrangThai VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    MaVT NUMBER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_nguoidung_trangthai CHECK (TrangThai IN ('ACTIVE', 'INACTIVE', 'BANNED')),
    CONSTRAINT fk_user_role FOREIGN KEY (MaVT) REFERENCES VAITRO(MaVT)
);

CREATE TABLE DIACHI (
    MaDC NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK NUMBER NOT NULL,
    TenDiaChi VARCHAR2(100),
    TenNguoiNhan VARCHAR2(100) NOT NULL,
    SDTNguoiNhan VARCHAR2(15) NOT NULL,
    DiaChiCuThe VARCHAR2(4000) NOT NULL,
    TinhThanh VARCHAR2(50) NOT NULL,
    QuanHuyen VARCHAR2(50) NOT NULL,
    PhuongXa VARCHAR2(50) NOT NULL,
    isDefault NUMBER(1) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_diachi_default CHECK (isDefault IN (0, 1)),
    CONSTRAINT fk_diachi_user FOREIGN KEY (MaTK) REFERENCES NGUOIDUNG(MaTK) ON DELETE CASCADE
);

CREATE TABLE DANHMUC (
    MaDM NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenDM VARCHAR2(100) NOT NULL,
    MoTa VARCHAR2(4000),
    imageUrl VARCHAR2(255),
    isAvailable NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_danhmuc_available CHECK (isAvailable IN (0, 1))
);

CREATE TABLE MONAN (
    MaMon NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenMon VARCHAR2(100) NOT NULL,
    MoTa VARCHAR2(4000),
    Gia NUMBER(15,2) NOT NULL,
    GiaGiam NUMBER(15,2) DEFAULT 0 NOT NULL,
    SoLuongTon NUMBER DEFAULT 0 NOT NULL,
    SoLuongDaBan NUMBER DEFAULT 0 NOT NULL,
    MaDM NUMBER NOT NULL,
    image_url VARCHAR2(255),
    IsAvailable NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_monan_gia CHECK (Gia >= 0),
    CONSTRAINT ck_monan_giagiam CHECK (GiaGiam >= 0),
    CONSTRAINT ck_monan_ton CHECK (SoLuongTon >= 0),
    CONSTRAINT ck_monan_daban CHECK (SoLuongDaBan >= 0),
    CONSTRAINT ck_monan_available CHECK (IsAvailable IN (0, 1)),
    CONSTRAINT fk_monan_danhmuc FOREIGN KEY (MaDM) REFERENCES DANHMUC(MaDM)
);

CREATE TABLE MAGIAMGIA (
    MaGG NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaCode VARCHAR2(50) NOT NULL UNIQUE,
    LoaiGiam VARCHAR2(20) NOT NULL,
    MucGiam NUMBER(15,2) NOT NULL,
    DieuKien NUMBER(15,2) DEFAULT 0 NOT NULL,
    SoLuong NUMBER DEFAULT 0 NOT NULL,
    SoLanSuDung NUMBER DEFAULT 0 NOT NULL,
    MoTa VARCHAR2(255),
    NgayBatDau TIMESTAMP,
    NgayKetThuc TIMESTAMP,
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_magg_loai CHECK (LoaiGiam IN ('PERCENTAGE', 'AMOUNT')),
    CONSTRAINT ck_magg_mucgiam CHECK (MucGiam >= 0),
    CONSTRAINT ck_magg_dieukien CHECK (DieuKien >= 0),
    CONSTRAINT ck_magg_soluong CHECK (SoLuong >= 0),
    CONSTRAINT ck_magg_solansudung CHECK (SoLanSuDung >= 0)
);

CREATE TABLE DONHANG (
    MaDH NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK_KH NUMBER NOT NULL,
    MaTK_NV NUMBER,
    NgayDat TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MaDC NUMBER,
    TongTienMon NUMBER(15,2) DEFAULT 0 NOT NULL,
    TienGiamGia NUMBER(15,2) DEFAULT 0 NOT NULL,
    ThanhTien NUMBER(15,2) DEFAULT 0 NOT NULL,
    TrangThaiDon VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    MaGG NUMBER,
    GhiChu CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_donhang_tongtienmon CHECK (TongTienMon >= 0),
    CONSTRAINT ck_donhang_tiengiamgia CHECK (TienGiamGia >= 0),
    CONSTRAINT ck_donhang_thanhtien CHECK (ThanhTien >= 0),
    CONSTRAINT ck_donhang_trangthai CHECK ( TrangThaiDon IN ('PENDING', 'CONFIRMED', 'SHIPPING', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT fk_donhang_khachhang FOREIGN KEY (MaTK_KH) REFERENCES NGUOIDUNG(MaTK),
    CONSTRAINT fk_donhang_nhanvien FOREIGN KEY (MaTK_NV) REFERENCES NGUOIDUNG(MaTK),
    CONSTRAINT fk_donhang_diachi FOREIGN KEY (MaDC) REFERENCES DIACHI(MaDC),
    CONSTRAINT fk_donhang_magiamgia FOREIGN KEY (MaGG) REFERENCES MAGIAMGIA(MaGG)
);

CREATE TABLE CHITIETDH (
    MaDH NUMBER NOT NULL,
    MaMon NUMBER NOT NULL,
    TenMon VARCHAR2(255) NOT NULL,
    SoLuong NUMBER NOT NULL,
    DonGia NUMBER(15,2) NOT NULL,
    ThanhTien NUMBER(15,2) NOT NULL,

    CONSTRAINT pk_chitietdh PRIMARY KEY (MaDH, MaMon),
    CONSTRAINT ck_ctdh_soluong CHECK (SoLuong > 0),
    CONSTRAINT ck_ctdh_dongia CHECK (DonGia >= 0),
    CONSTRAINT ck_ctdh_thanhtien CHECK (ThanhTien >= 0),
    CONSTRAINT fk_ctdh_donhang FOREIGN KEY (MaDH) REFERENCES DONHANG(MaDH) ON DELETE CASCADE,
    CONSTRAINT fk_ctdh_monan FOREIGN KEY (MaMon) REFERENCES MONAN(MaMon)
);

CREATE TABLE PHUONGTHUCTT (
    MaPT VARCHAR2(20) PRIMARY KEY,
    TenPT VARCHAR2(50) NOT NULL
);

CREATE TABLE THANHTOAN (
    MaTT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaDH NUMBER NOT NULL,
    MaPT VARCHAR2(20) NOT NULL,
    NgayTT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    SoTien NUMBER(15,2) NOT NULL,
    TrangThaiTT VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,

    CONSTRAINT ck_thanhtoan_sotien CHECK (SoTien >= 0),
    CONSTRAINT ck_thanhtoan_trangthai CHECK (TrangThaiTT IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED')),
    CONSTRAINT fk_thanhtoan_donhang FOREIGN KEY (MaDH) REFERENCES DONHANG(MaDH),
    CONSTRAINT fk_thanhtoan_pttt FOREIGN KEY (MaPT) REFERENCES PHUONGTHUCTT(MaPT)
);

CREATE TABLE DANHGIA (
    MaDG NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK_KH NUMBER NOT NULL,
    MaMon NUMBER NOT NULL,
    MaDH NUMBER NOT NULL,
    Sao NUMBER NOT NULL,
    NoiDung VARCHAR2(4000),
    AnhDG VARCHAR2(255),
    NgayDG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_danhgia_sao CHECK (Sao BETWEEN 1 AND 5),
    CONSTRAINT uq_review UNIQUE (MaTK_KH, MaMon, MaDH),
    CONSTRAINT fk_danhgia_user FOREIGN KEY (MaTK_KH) REFERENCES NGUOIDUNG(MaTK),
    CONSTRAINT fk_danhgia_ctdh FOREIGN KEY (MaDH, MaMon) REFERENCES CHITIETDH(MaDH, MaMon)
);

CREATE TABLE KHUYENMAI (
    MaKM NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PhanTramGiam NUMBER(5,2),
    TenKM VARCHAR2(100) NOT NULL,
    PhamViApDung VARCHAR2(20),
    NgayBatDau TIMESTAMP,
    NgayKetThuc TIMESTAMP
);

CREATE TABLE CHITIETKHUYENMAI (
    MaKM NUMBER NOT NULL,
    MaMon NUMBER NOT NULL,
    PhanTramGiam NUMBER,

    CONSTRAINT pk_chitietkhuyenmai PRIMARY KEY (MaKM, MaMon),
    CONSTRAINT ck_ctkm_phantram CHECK (PhanTramGiam BETWEEN 0 AND 100),
    CONSTRAINT fk_ctkm_khuyenmai FOREIGN KEY (MaKM) REFERENCES KHUYENMAI(MaKM) ON DELETE CASCADE,
    CONSTRAINT fk_ctkm_monan FOREIGN KEY (MaMon) REFERENCES MONAN(MaMon)
);

CREATE TABLE YEUCAUHOTRO (
    MaYC NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK_KH NUMBER NOT NULL,
    MaTK_NV NUMBER,
    TieuDe VARCHAR2(255) NOT NULL,
    NoiDung VARCHAR2(4000),
    TrangThai VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_ycht_trangthai CHECK (TrangThai IN ('PENDING', 'PROCESSING', 'DONE')),
    CONSTRAINT fk_ycht_kh FOREIGN KEY (MaTK_KH) REFERENCES NGUOIDUNG(MaTK),
    CONSTRAINT fk_ycht_nv FOREIGN KEY (MaTK_NV) REFERENCES NGUOIDUNG(MaTK)
);

CREATE TABLE CHITIETHOTRO (
    MaChat NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaYC NUMBER NOT NULL,
    MaTK_Gui NUMBER NOT NULL,
    NoiDung VARCHAR2(2000) NOT NULL,
    NgayGui TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ctht_yc FOREIGN KEY (MaYC) REFERENCES YEUCAUHOTRO(MaYC) ON DELETE CASCADE,
    CONSTRAINT fk_ctht_tk FOREIGN KEY (MaTK_Gui) REFERENCES NGUOIDUNG(MaTK)
);

CREATE TABLE LICHSUTRANGTHAIDH (
    MaLS NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaDH NUMBER NOT NULL,
    TrangThaiCu VARCHAR2(30),
    TrangThaiMoi VARCHAR2(30) NOT NULL,
    MaNguoiThucHien NUMBER,
    LyDo CLOB,
    ThoiGian TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT ck_lstt_trangthai_moi CHECK (TrangThaiMoi IN ('PENDING', 'CONFIRMED', 'SHIPPING', 'DELIVERED', 'CANCEL_REQUESTED', 'CANCELLED')),
    CONSTRAINT fk_lstt_donhang FOREIGN KEY (MaDH) REFERENCES DONHANG(MaDH) ON DELETE CASCADE
);



CREATE INDEX idx_lstt_donhang_time ON LICHSUTRANGTHAIDH (MaDH, ThoiGian);
