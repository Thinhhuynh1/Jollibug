-- Drop tables in reverse dependency order
DROP TABLE CHITIETHOTRO CASCADE CONSTRAINTS;
DROP TABLE YEUCAUHOTRO CASCADE CONSTRAINTS;
DROP TABLE CHITIETGIAMGIA CASCADE CONSTRAINTS;
DROP TABLE CHUONGTRINHGIAMGIA CASCADE CONSTRAINTS;
DROP TABLE DANHGIA CASCADE CONSTRAINTS;
DROP TABLE THANHTOAN CASCADE CONSTRAINTS;
DROP TABLE PHUONGTHUCTT CASCADE CONSTRAINTS;
DROP TABLE CHITIETDH CASCADE CONSTRAINTS;
DROP TABLE DONHANG CASCADE CONSTRAINTS;
DROP TABLE MAGIAMGIA CASCADE CONSTRAINTS;
DROP TABLE MONAN CASCADE CONSTRAINTS;
DROP TABLE DANHMUC CASCADE CONSTRAINTS;
DROP TABLE CHITIETGH CASCADE CONSTRAINTS;
DROP TABLE DIACHI CASCADE CONSTRAINTS;
DROP TABLE NGUOIDUNG CASCADE CONSTRAINTS;
DROP TABLE VAITRO CASCADE CONSTRAINTS;

CREATE TABLE VAITRO (
    MaVT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenVT VARCHAR2(50) NOT NULL
);

CREATE TABLE NGUOIDUNG (
    MaTK NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Password VARCHAR2(255) NOT NULL,
    HoTen VARCHAR2(100) NOT NULL,
    SDT VARCHAR2(15),
    Email VARCHAR2(100) UNIQUE NOT NULL,
    TrangThai VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (TrangThai IN ('ACTIVE', 'INACTIVE', 'BANNED')),
    MaVT NUMBER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_role FOREIGN KEY (MaVT) REFERENCES VAITRO(MaVT)
);

CREATE TABLE DIACHI (
    MaDC NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK NUMBER NOT NULL,
    TenDiaChi VARCHAR2(100),
    TenNguoiNhan VARCHAR2(100) NOT NULL,
    SDTNguoiNhan VARCHAR2(15) NOT NULL,
    DiaChiCuThe VARCHAR2(4000) NOT NULL,
    TinhThanh VARCHAR2(50) NOT NULL,
    QuanHuyen VARCHAR2(50) NOT NULL,
    PhuongXa VARCHAR2(50) NOT NULL,
    isDefault NUMBER(1) DEFAULT 0 CHECK (isDefault IN (0,1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_diachi_user FOREIGN KEY (MaTK) REFERENCES NGUOIDUNG(MaTK) ON DELETE CASCADE
);

CREATE TABLE CHITIETGH (
    MaGH NUMBER NOT NULL,
    MaMon NUMBER NOT NULL,
    SLuong NUMBER DEFAULT 1,
    PRIMARY KEY (MaGH, MaMon)
);

CREATE TABLE DANHMUC (
    MaDM NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenDM VARCHAR2(100) NOT NULL,
    MoTa VARCHAR2(4000),
    imageUrl VARCHAR2(255),
    isAvailable NUMBER(1) DEFAULT 1 CHECK (isAvailable IN (0,1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE MONAN (
    MaMon NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TenMon VARCHAR2(100) NOT NULL,
    MoTa VARCHAR2(4000),
    Gia NUMBER(15,2) NOT NULL CHECK (Gia >= 0),
    GiaGiam NUMBER(15,2) DEFAULT 0 CHECK (GiaGiam >= 0),
    SoLuongTon NUMBER DEFAULT 0 CHECK (SoLuongTon >= 0),
    SoLuongDaBan NUMBER DEFAULT 0 CHECK (SoLuongDaBan >= 0),
    MaDM NUMBER NOT NULL,
    image_url VARCHAR2(255),
    IsAvailable NUMBER(1) DEFAULT 1 CHECK (IsAvailable IN (0,1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_monan_danhmuc FOREIGN KEY (MaDM) REFERENCES DANHMUC(MaDM)
);

CREATE TABLE MAGIAMGIA (
    MaGG NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MA_CODE VARCHAR2(50) UNIQUE NOT NULL,
    LoaiGiam VARCHAR2(20) NOT NULL CHECK (LoaiGiam IN ('PERCENTAGE', 'AMOUNT')),
    MucGiam NUMBER(15,2) NOT NULL CHECK (MucGiam >= 0),
    SoLuong NUMBER DEFAULT 0,
    MoTa VARCHAR2(255),
    NgayBatDau TIMESTAMP,
    NgayKetThuc TIMESTAMP,
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE DONHANG (
    MaDH NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK NUMBER NOT NULL,
    TongTien NUMBER(15,2) DEFAULT 0,
    TrangThai VARCHAR2(20) DEFAULT 'Pending' CHECK (
            TrangThai IN (
                'Pending',
                'Confirmed',
                'Shipping',
                'Delivered',
                'Cancelled'
            )
        ),
    DiaChiGiaoHang VARCHAR2(4000),
    SDTNhanHang VARCHAR2(15),
    GhiChu VARCHAR2(4000),
    NgayDat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_donhang_user FOREIGN KEY (MaTK) REFERENCES NGUOIDUNG(MaTK)
);

CREATE TABLE CHITIETDH (
    MaDH NUMBER,
    MaMon NUMBER,
    SoLuong NUMBER NOT NULL CHECK (SoLuong > 0),
    DonGia NUMBER(15,2) NOT NULL CHECK (DonGia >= 0),
    PRIMARY KEY (MaDH, MaMon),

    CONSTRAINT fk_ctdh_donhang FOREIGN KEY (MaDH) REFERENCES DONHANG(MaDH) ON DELETE CASCADE,
    CONSTRAINT fk_ctdh_monan FOREIGN KEY (MaMon) REFERENCES MONAN(MaMon)
);

CREATE TABLE PHUONGTHUCTT (
    MaPT VARCHAR2(20) PRIMARY KEY,
    TenPT VARCHAR2(50) NOT NULL
);

CREATE TABLE THANHTOAN (
    MaTT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaDH NUMBER NOT NULL,
    MaPT VARCHAR2(20) NOT NULL,
    NgayTT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    SoTien NUMBER(15,2) NOT NULL CHECK (SoTien >= 0),
    TrangThaiTT VARCHAR2(20) DEFAULT 'Pending' CHECK (TrangThaiTT IN ('Pending', 'Paid', 'Failed')),

    CONSTRAINT fk_thanhtoan_donhang FOREIGN KEY (MaDH) REFERENCES DONHANG(MaDH),
    CONSTRAINT fk_thanhtoan_pttt FOREIGN KEY (MaPT) REFERENCES PHUONGTHUCTT(MaPT)
);

CREATE TABLE DANHGIA (
    MaDG NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK_KH NUMBER NOT NULL,
    MaMon NUMBER NOT NULL,
    MaDH NUMBER NOT NULL,
    Sao NUMBER CHECK (Sao BETWEEN 1 AND 5),
    NoiDung VARCHAR2(4000),
    NgayDG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_review UNIQUE (MaTK_KH, MaMon, MaDH),
    CONSTRAINT fk_danhgia_user FOREIGN KEY (MaTK_KH) REFERENCES NGUOIDUNG(MaTK),
    CONSTRAINT fk_danhgia_monan FOREIGN KEY (MaMon) REFERENCES MONAN(MaMon),
    CONSTRAINT fk_danhgia_donhang FOREIGN KEY (MaDH) REFERENCES DONHANG(MaDH)
);

CREATE TABLE CHUONGTRINHGIAMGIA (
    MaCT NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PhanTramGiam NUMBER(5,2),
    TenCT VARCHAR2(100) NOT NULL,
    PhamViApDung VARCHAR2(20),
    MaDM NUMBER,
    DanhSachMonAn VARCHAR2(1000),
    NgayBatDau TIMESTAMP,
    NgayKetThuc TIMESTAMP
);

CREATE TABLE CHITIETGIAMGIA (
    MaCT NUMBER,
    MaMon NUMBER,
    PhanTramGiam NUMBER CHECK (PhanTramGiam BETWEEN 0 AND 100),
    PRIMARY KEY (MaCT, MaMon),

    CONSTRAINT fk_ctgg_ct FOREIGN KEY (MaCT) REFERENCES CHUONGTRINHGIAMGIA(MaCT) ON DELETE CASCADE,
    CONSTRAINT fk_ctgg_monan FOREIGN KEY (MaMon) REFERENCES MONAN(MaMon)
);

CREATE TABLE YEUCAUHOTRO (
    MaYC NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaTK_KH NUMBER NOT NULL,
    MaTK_NV NUMBER,
    TieuDe VARCHAR2(255) NOT NULL,
    NoiDung VARCHAR2(4000),
    TrangThai VARCHAR2(20) DEFAULT 'Pending' CHECK (
        TrangThai IN ('Pending', 'Processing', 'Done')
    ),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ycht_kh FOREIGN KEY (MaTK_KH) REFERENCES NGUOIDUNG(MaTK),
    CONSTRAINT fk_ycht_nv FOREIGN KEY (MaTK_NV) REFERENCES NGUOIDUNG(MaTK)
);

CREATE TABLE CHITIETHOTRO (
    MaChat NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MaYC NUMBER NOT NULL,
    MaTK_Gui NUMBER NOT NULL,
    NoiDung VARCHAR2(2000) NOT NULL,
    NgayGui TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ctht_yc FOREIGN KEY (MaYC) REFERENCES YEUCAUHOTRO(MaYC),
    CONSTRAINT fk_ctht_tk FOREIGN KEY (MaTK_Gui) REFERENCES NGUOIDUNG(MaTK)
);
