-- 2. TẠO BẢNG ĐƠN HÀNG
-- =========================

CREATE TABLE DONHANG (
    MaDH NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    MaTK_KH NUMBER NOT NULL,
    MaTK_NV NUMBER,

    NgayDat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    MaDC NUMBER,

    TongTienMon NUMBER(15, 2) NOT NULL,
    TienGiamGia NUMBER(15, 2) DEFAULT 0,
    ThanhTien NUMBER(15, 2) NOT NULL,

    TrangThaiDon VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,

    MaGG NUMBER,
    GhiChu CLOB,

    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT CK_DONHANG_TRANGTHAI CHECK (
        TrangThaiDon IN (
            'PENDING',
            'CONFIRMED',
            'SHIPPING',
            'DELIVERED',
            'CANCEL_REQUESTED',
            'CANCELLED'
        )
    )
);

-- =========================
-- 3. TẠO BẢNG CHI TIẾT ĐƠN HÀNG
