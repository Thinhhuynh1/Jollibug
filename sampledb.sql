CREATE TABLE LICHSUTRANGTHAIDH (
    MaLS NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    MaDH NUMBER NOT NULL,

    TrangThaiCu VARCHAR2(30),
    TrangThaiMoi VARCHAR2(30) NOT NULL,

    NguoiThucHienLoai VARCHAR2(20) DEFAULT 'SYSTEM' NOT NULL,
    MaNguoiThucHien NUMBER,

    LyDo CLOB,
    ThoiGian TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT FK_LSTT_DONHANG
        FOREIGN KEY (MaDH)
        REFERENCES DONHANG(MaDH)
        ON DELETE CASCADE,

    CONSTRAINT CK_LSTT_TRANGTHAI_MOI CHECK (
        TrangThaiMoi IN (
            'PENDING',
            'CONFIRMED',
            'SHIPPING',
            'DELIVERED',
            'CANCEL_REQUESTED',
            'CANCELLED'
        )
    ),

    CONSTRAINT CK_LSTT_NGUOI_THUC_HIEN CHECK (
        NguoiThucHienLoai IN (
            'CUSTOMER',
            'STAFF',
            'MANAGER',
            'ADMIN',
            'SYSTEM'
        )
    )
);

CREATE INDEX IDX_LSTT_DONHANG_TIME
ON LICHSUTRANGTHAIDH (MaDH, ThoiGian);

INSERT INTO LICHSUTRANGTHAIDH (
    MaDH,
    TrangThaiCu,
    TrangThaiMoi,
    NguoiThucHienLoai,
    MaNguoiThucHien,
    LyDo,
    ThoiGian
)
SELECT
    MaDH,
    'PENDING',
    TrangThaiDon,
    CASE
        WHEN TrangThaiDon = 'CANCELLED' AND MaTK_NV IS NULL THEN 'CUSTOMER'
        WHEN MaTK_NV IS NOT NULL THEN 'STAFF'
        ELSE 'SYSTEM'
    END,
    CASE
        WHEN MaTK_NV IS NOT NULL THEN MaTK_NV
        ELSE MaTK_KH
    END,
    'Bổ sung trạng thái hiện tại từ dữ liệu cũ',
    CURRENT_TIMESTAMP
FROM DONHANG d
WHERE TrangThaiDon <> 'PENDING'
AND NOT EXISTS (
    SELECT 1
    FROM LICHSUTRANGTHAIDH ls
    WHERE ls.MaDH = d.MaDH
    AND ls.TrangThaiMoi = d.TrangThaiDon
);
